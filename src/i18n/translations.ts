const days: Record<string, string> = {
  lunes: "Monday", martes: "Tuesday", miércoles: "Wednesday", jueves: "Thursday", viernes: "Friday", sábado: "Saturday", domingo: "Sunday",
};

export function translateLegacyText(language: Language, source: string): string {
  if (language === "es" || !source.trim()) return source;
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  const clean = source.trim();
  let translated = en[clean];
  if (!translated) {
    translated = clean
      .replace(/\b(enero|febrero|marzo|abril|mayo|junio|julio|agosto|septiembre|octubre|noviembre|diciembre)\b/gi, (match) => months[match.toLowerCase()] ?? match)
      .replace(/\b(lunes|martes|miércoles|jueves|viernes|sábado|domingo)\b/gi, (match) => days[match.toLowerCase()] ?? match)
      .replace(/^([A-Za-z]+), (\d+) de ([A-Za-z]+)$/i, "$1, $3 $2")
      .replace(/^(\d+) de ([A-Za-z]+) de (\d{4})$/i, "$2 $1, $3")
      .replace(/^(\d+) de ([A-Za-z]+)$/i, "$2 $1")
      .replace(/^(\d+) de (\d+) hábitos$/, "$1 of $2 habits")
      .replace(/^(\d+) de (\d+) tareas$/, "$1 of $2 tasks")
      .replace(/^(.+) ahorrados$/, "$1 saved")
      .replace(/^Prioridad (\d+)$/, "Priority $1")
      .replace(/^Energía (\d+)\/5$/, "Energy $1/5")
      .replace(/^Paso (\d+) de (\d+)$/, "Step $1 of $2")
      .replace(/^Serie (\d+)$/, "Set $1")
      .replace(/^(\d+) repeticiones$/, "$1 reps")
      .replace(/^Planificar (.+) (\d{4})$/, "Plan $1 $2")
      .replace(/^Editar (.+) (\d{4})$/, "Edit $1 $2")
      .replace(/^(\d+) de (\d+) prioridades completadas$/, "$1 of $2 priorities completed")
      .replace(/^(\d+) tareas$/, "$1 tasks")
      .replace(/^(\d+) abiertas$/, "$1 open")
      .replace(/^Añadir a (.+)$/i, (_, label: string) => `Add to ${en[label] ?? label}`)
      .replace(/^Guardar en (.+)$/i, (_, label: string) => `Save to ${en[label] ?? label}`)
      .replace(/^Diseñar mi visión de (.+)$/i, (_, label: string) => `Design my vision for ${(en[label[0]?.toUpperCase() + label.slice(1)] ?? label).toLowerCase()}`)
      .replace(/^Reflexión · (.+)$/i, "Reflection · $1")
      .replace(/^Ahora · (.+)$/i, "Current · $1")
      .replace(/^Ver mi (Monday|Tuesday|Wednesday|Thursday|Friday|Saturday|Sunday)$/i, "View my $1")
      .replace(/^Objetivo para (.+)$/, "Goal for $1")
      .replace(/^Relacionado con:/, "Related to:");
  }
  return `${leading}${translated}${trailing}`;
}

